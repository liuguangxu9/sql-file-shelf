// Run in an isolated Edge test origin seeded with the documented OPFS fixture.
// Does not access user directories. Evaluate this IIFE via agent-browser eval -b.
(async () => {
  const $ = id => document.getElementById(id);
  const checks = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  const wait = async predicate => {
    for (let index=0; index<100; index++) {
      if (predicate()) return;
      await new Promise(resolve => setTimeout(resolve,30));
    }
    throw new Error('UI timeout');
  };
  const editor = $('editor');
  const open = async name => {
    document.querySelector(`.fileRow[data-path="${name}"]`).click();
    await wait(() => $('fileTitle').textContent === name);
  };
  const input = (element, value) => { element.value=value; element.dispatchEvent(new Event('input',{bubbles:true})); };
  const key = (name, options={}) => editor.dispatchEvent(new KeyboardEvent('keydown',{key:name,bubbles:true,...options}));
  await open('医嘱查询.sql');
  const original=editor.value;
  input(editor, original+'-- draft A\n');
  editor.setSelectionRange(4,7);
  await open('费用核对.sql');
  const second=editor.value;
  input(editor, second+'-- draft B\n');
  await open('医嘱查询.sql');
  assert(editor.value===original+'-- draft A\n','tab A retains draft');
  assert(editor.selectionStart===4 && editor.selectionEnd===7,'tab retains selection');
  assert(document.querySelectorAll('.editorTab').length===2,'two independent tabs');
  key('z',{ctrlKey:true});
  assert(editor.value===original,'tab A undo is independent');
  await open('费用核对.sql');
  assert(editor.value===second+'-- draft B\n','tab B draft unaffected by A undo');
  key('z',{ctrlKey:true});
  assert(editor.value===second,'tab B undo is independent');
  $('replaceFile').click();
  input($('findInput'),'patient_id'); input($('replaceInput'),'patient_key');
  $('replaceAll').click();
  assert(editor.value.includes('patient_key') && !editor.value.includes('patient_id'),'replace all changes matches');
  key('z',{ctrlKey:true});
  assert(editor.value===second,'replace all is one undo step');
  $('closeFind').click();
  $('favoriteFile').click();
  assert($('favoriteFile').textContent.includes('已收藏'),'favorite toggles');
  document.querySelector('[data-view="favorites"]').click();
  assert($('collectionList').textContent.includes('费用核对.sql'),'favorite visible in collection');
  document.querySelector('[data-view="recent"]').click();
  assert($('collectionList').textContent.includes('医嘱查询.sql'),'recent files collected');
  document.querySelector('[data-view="files"]').click();
  assert(!$('contentSearch'),'standalone full-text search removed');
  assert(document.querySelector('.localBadge').textContent==='文件不上传','local storage label is plain language');
  $('quickOpen').click(); input($('globalSearch'),'no-such-file'); input($('globalSearch'),'费用核对');
  await wait(() => $('globalResults').querySelector('.result'));
  assert($('globalResults').textContent.includes('费用核对.sql') && !$('globalResults').textContent.includes('医嘱查询.sql'),'latest quick search wins');
  $('closeSearch').click();
  await open('费用核对.sql');
  input(editor,second+'-- saved revision\n');
  $('save').click();
  assert(document.querySelector('main').inert,'save locks editing during asynchronous write');
  await wait(() => !document.querySelector('main').inert);
  const root=await navigator.storage.getDirectory();
  const dir=await root.getDirectoryHandle('SQL 演示工作区');
  const handle=await dir.getFileHandle('费用核对.sql');
  assert(await (await handle.getFile()).text()===second+'-- saved revision\n','save writes selected tab');
  const backup=await dir.getFileHandle('费用核对.sql.bak');
  assert(await (await backup.getFile()).text()===second,'save backs up prior bytes');
  const writer=await handle.createWritable();await writer.write('-- external change\nSELECT 123;');await writer.close();
  input(editor,editor.value+'-- conflict draft\n');$('save').click();
  await wait(() => document.querySelector('.conflictDialog[open]'));
  const dialog=document.querySelector('.conflictDialog');
  assert(dialog.textContent.includes('-- external change'),'external conflict shows disk contents');
  const cancel=[...dialog.querySelectorAll('button')].find(b=>b.textContent.includes('取消'));
  cancel.click(); await wait(()=>!document.querySelector('main').inert);
  assert(editor.value.includes('-- conflict draft'),'cancel conflict keeps draft');
  $('save').click();await wait(()=>document.querySelector('.conflictDialog[open]'));
  const reload=[...document.querySelector('.conflictDialog').querySelectorAll('button')].find(b=>b.textContent.includes('重新加载'));
  reload.click(); await wait(()=>!document.querySelector('main').inert);
  assert(editor.value==='-- external change\nSELECT 123;','reload conflict bypasses old tab snapshot');
  assert(document.querySelectorAll('.editorTab').length===2,'reload does not duplicate tab');
  $('manageWorkspaces').click();
  [...document.querySelectorAll('#workspaceList .workspace button')].find(b=>b.textContent.includes('第二工作区')).click();
  await wait(()=>document.querySelector('.fileRow[data-path="GBK测试.sql"]'));
  assert(!$('workspaceDialog').open,'successful workspace selection closes manager');
  await open('GBK测试.sql');
  assert(editor.value.includes('中文'),'GBK file decodes');
  assert($('encoding').textContent==='GBK','GBK metadata retained');
  input(editor,editor.value+'-- added');$('save').click();await wait(()=>!document.querySelector('main').inert);
  const other=await root.getDirectoryHandle('第二工作区');
  const gbk=new Uint8Array(await (await (await other.getFileHandle('GBK测试.sql')).getFile()).arrayBuffer());
  assert(gbk[3]===0xd6 && gbk[4]===0xd0 && gbk[7]===13 && gbk[8]===10,'GBK bytes and CRLF preserved');
  [...document.querySelectorAll('#editorTabs .editorTab > button:first-child')].find(b=>b.textContent.includes('医嘱查询.sql')).click();
  assert(editor.value===original,'cross-workspace tab restores previous content');
  const oldConfirm=window.confirm;let prompts=0;window.confirm=()=>{prompts++;return false;};
  document.querySelector('.editorTab.selected .closeTab').click();
  window.confirm=oldConfirm;
  assert(prompts===1 && $('fileTitle').textContent==='医嘱查询.sql','cancel dirty-tab close preserves tab');
  $('save').click();await wait(()=>!document.querySelector('main').inert);
  document.querySelector('.editorTab.selected .closeTab').click();
  assert(document.querySelectorAll('.editorTab').length===2,'clean tab closes');
  key('t',{ctrlKey:true,shiftKey:true});await wait(()=>$('fileTitle').textContent==='医嘱查询.sql');
  assert(document.querySelectorAll('.editorTab').length===3,'recently closed tab reopens');
  assert(document.documentElement.scrollWidth<=innerWidth,'desktop has no horizontal overflow');
  return {passed:checks.length,checks};
})()
